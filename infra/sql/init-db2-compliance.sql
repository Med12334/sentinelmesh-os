-- Layer 9: IBM DB2 NIS2 & ISO-27001 Regulatory Security Audit Vault
CREATE TABLE COMPLIANCE_AUDIT_VAULT (
    AUDIT_SEQ_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 900000, INCREMENT BY 1),
    INCIDENT_REF_UUID CHAR(36) NOT NULL,
    ATTACKER_IP VARCHAR(64) NOT NULL,
    MITRE_TACTIC_CODE VARCHAR(32) NOT NULL,
    SEVERITY_SCORE DECIMAL(4, 2) NOT NULL,
    SOAR_ACTION_TAKEN VARCHAR(64) NOT NULL,
    MERKLE_PROOF_HASH CHAR(64) NOT NULL,
    REGULATORY_FRAMEWORK VARCHAR(32) NOT NULL,
    ARCHIVED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (AUDIT_SEQ_ID)
);

CREATE INDEX IDX_DB2_INCIDENT_UUID ON COMPLIANCE_AUDIT_VAULT(INCIDENT_REF_UUID);
CREATE INDEX IDX_DB2_MITRE_CODE ON COMPLIANCE_AUDIT_VAULT(MITRE_TACTIC_CODE);
